// Build web/lib/starColorTable.ts: blackbody colour (sRGB, D65 white) by temperature, from
// Mitchell Charity's "What color is a blackbody?" table (CIE 1964 10 degree observer rows).
//
//   node web/scripts/build-star-colors.mjs
//
// Source: http://www.vendian.org/mncharity/dir3/blackbody/UnstableURLs/bbr_color.html
// (context: http://www.vendian.org/mncharity/dir3/starcolor/). Rows run 1000 K to 40000 K in 100 K steps.

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const URL = "http://www.vendian.org/mncharity/dir3/blackbody/UnstableURLs/bbr_color.html";

const res = await fetch(URL);
if (!res.ok) throw new Error(`${URL}: ${res.status}`);
const html = await res.text();

// "  5800 K  10deg  0.3234 0.3372 ...  255 238 222  #ffeede"
const rows = [...html.matchAll(/(\d+) K\s+10deg\s[^\n]*?(#[0-9a-f]{6})\s*<\/span>/gi)].map((m) => [Number(m[1]), m[2]]);
if (rows.length !== 391 || rows[0][0] !== 1000 || rows.at(-1)[0] !== 40000) {
  throw new Error(`unexpected table shape: ${rows.length} rows, ${rows[0]?.[0]} to ${rows.at(-1)?.[0]} K`);
}
const hex = rows.map(([, h]) => h.slice(1)).join("");

const out = `// Generated by scripts/build-star-colors.mjs. Do not edit.
// Blackbody sRGB colour (D65 white, CIE 1964 10 degree observer), Mitchell Charity,
// http://www.vendian.org/mncharity/dir3/blackbody/UnstableURLs/bbr_color.html
// 391 entries: 1000 K to 40000 K in 100 K steps, 6 hex digits each.

export const BB_T_MIN = 1000;
export const BB_T_STEP = 100;
export const BB_HEX =
  "${hex.match(/.{1,96}/g).join('" +\n  "')}";
`;
await writeFile(path.join(here, "..", "lib", "starColorTable.ts"), out);
console.log(`starColorTable.ts: ${rows.length} rows`);
